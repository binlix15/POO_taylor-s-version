package db;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class Database {

    // Aqui va el link de mi base de datos en Neon (no subir la clave real a Git)
    // jdbc:postgresql://localhost:5432/nombre_bd
    private static final String URL = "jdbc:postgresql://neon/neondb?user=user&password=password&sslmode=require&channelBinding=require";

    public static Connection connect() throws SQLException {
        return DriverManager.getConnection(URL);
    }

    public static void createTable() {
        // GENERATED BY DEFAULT AS IDENTITY hace que el id se ponga solo (1, 2, 3...)
        String sql = "CREATE TABLE IF NOT EXISTS albums " +
                "(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "name TEXT NOT NULL," +
                "release_year INT NOT NULL," +
                "singles TEXT," +
                "rerecorded BOOLEAN NOT NULL," +
                "favorite BOOLEAN NOT NULL)";

        try (Connection conn = connect();
             Statement st = conn.createStatement()) {
            st.execute(sql);
        } catch (SQLException e) {
            System.out.println("El error es: " + e.getMessage());
        }
    }

}